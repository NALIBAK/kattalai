export function useTranslation() {
  const language = useSettingsStore(state => state.language) || 'ta';
  
  const t = (key: keyof typeof translations.ta) => {
    const dict = translations[language] || translations.ta;
    return dict[key] || translations.ta[key] || key;
  };
  
  return { t, language };
}
